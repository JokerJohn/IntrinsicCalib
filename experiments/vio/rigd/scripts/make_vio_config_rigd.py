#!/usr/bin/env python3
"""OpenVINS mono config for one Rig-D intrinsics set (pre-rectified, zero distortion).
  make_vio_config_rigd.py <rect.bag.K.yaml> <out_dir> --td <timeshift_cam_imu [s]>
Fixed for every set: T_cam_imu = T_cam_lidar (extrinsics/extrinsic_cam_lidar.yaml) * T_lidar_imu (identity, FPV2 convention,
), timeshift_cam_imu = td (t_imu = t_cam + td), IMU chain and estimator settings from rigd/vio_templates.
Varies: fx fy cx cy of the set (already scaled to the 960x540 rectified images).
"""
import argparse, os, shutil, yaml, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); RIGD = os.path.dirname(HERE)
EXT = os.environ.get('RIGD_EXTRINSIC', f'{RIGD}/extrinsics/extrinsic_cam_lidar.yaml')   # camera-LiDAR extrinsic of the Rig-D platform
ap = argparse.ArgumentParser(); ap.add_argument('kyaml'); ap.add_argument('out_dir'); ap.add_argument('--td', type=float, required=True)
a = ap.parse_args()
k = yaml.safe_load(open(a.kyaml)); e = yaml.safe_load(open(EXT))
T_cam_lidar = np.array(e['T_cam_lidar'], float); T_lidar_imu = np.eye(4); T_cam_imu = T_cam_lidar @ T_lidar_imu
ov = os.path.join(a.out_dir, 'openvins'); os.makedirs(ov, exist_ok=True)
shutil.copy(f'{RIGD}/vio_templates/openvins_estimator_config.yaml', f'{ov}/estimator_config.yaml')
shutil.copy(f'{RIGD}/vio_templates/openvins_kalibr_imu_chain.yaml', f'{ov}/kalibr_imu_chain.yaml')
rows = '\n'.join('    - [%s]' % ', '.join(repr(float(x)) for x in r) for r in T_cam_imu)
open(f'{ov}/kalibr_imucam_chain.yaml', 'w').write(f'''%YAML:1.0

# generated by make_vio_config_rigd.py from {a.kyaml} (pre-rectified with the full model of {k['source']}, zero distortion)
# T_cam_imu = T_cam_lidar (extrinsics/extrinsic_cam_lidar.yaml) * T_lidar_imu (identity); timeshift_cam_imu = {a.td} s (t_imu = t_cam + shift), fixed for all sets
cam0:
  T_cam_imu:
{rows}
  cam_overlaps: []
  camera_model: pinhole
  distortion_coeffs: [0.0, 0.0, 0.0, 0.0]
  distortion_model: radtan
  intrinsics: [{k['fx']!r}, {k['fy']!r}, {k['cx']!r}, {k['cy']!r}]
  resolution: [{k['width']}, {k['height']}]
  rostopic: /cam0/image_raw
  timeshift_cam_imu: {a.td!r}
''')
print('wrote', ov)
