#!/usr/bin/env python3
"""Generate per-run OpenVINS configs from one intrinsics file.

  make_vio_config.py <intrinsics.yaml> <out_dir> [--drop_k3]
  make_vio_config.py --cam0 <cam0_set.yaml> --cam1 <cam1_set.yaml> --rectified <out_dir>

<intrinsics.yaml>: cam0: {fx, fy, cx, cy, k1, k2, p1, p2, k3}  (cam1 optional; Kalibr cam1 used if absent)
--cam0/--cam1: rap_eval format (cam_fx cam_fy cam_cx cam_cy cam_d0..cam_d4). With --rectified the images are
assumed pre-rectified with the full 5-coefficient model (scripts/make_rect_bag.py): the configs get the set's
fx fy cx cy and ZERO distortion, so k3 is handled exactly for every set.
Everything else (T_cam_imu, timeshift_cam_imu, stereo baseline, IMU noise, estimator settings) is fixed from
Kalibr calib-camchain-imu0-cam.yaml / imu0.yaml and the templates in this directory.
Output:
  <out_dir>/openvins/{estimator_config.yaml, kalibr_imu_chain.yaml, kalibr_imucam_chain.yaml}
"""
import argparse, os, shutil, sys, yaml, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))                # repository root
KAL = os.path.join(ROOT, 'data', 'rigc', 'kalibr_D2')                        # Kalibr camchain of session D2
RES = (1440, 1080)
def mat_rows(M): return '\n'.join('    - [%s]' % ', '.join(repr(float(x)) for x in row) for row in np.array(M))
def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('intrinsics', nargs='?'); ap.add_argument('out_dir')
    ap.add_argument('--cam0'); ap.add_argument('--cam1'); ap.add_argument('--rectified', action='store_true')
    ap.add_argument('--drop_k3', action='store_true', help='allow k3 != 0 in the input and silently drop it')
    a = ap.parse_args()
    if a.cam0:
        intr = {}
        for c, f in (('cam0', a.cam0), ('cam1', a.cam1)):
            if f:
                d = yaml.safe_load(open(f))
                intr[c] = {'fx': d['cam_fx'], 'fy': d['cam_fy'], 'cx': d['cam_cx'], 'cy': d['cam_cy'],
                           'k1': d['cam_d0'], 'k2': d['cam_d1'], 'p1': d['cam_d2'], 'p2': d['cam_d3'], 'k3': d.get('cam_d4', 0.0)}
        a.intrinsics = ' + '.join(os.path.relpath(os.path.abspath(f), ROOT) for f in (a.cam0, a.cam1) if f)
    else:
        intr = yaml.safe_load(open(a.intrinsics))
    kal = yaml.safe_load(open(f'{KAL}/calib-camchain-imu0-cam.yaml'))
    cams = {}
    for c in ('cam0', 'cam1'):
        if c in intr:
            d = intr[c]; K = [d['fx'], d['fy'], d['cx'], d['cy']]; D = [d['k1'], d['k2'], d['p1'], d['p2']]
            k3 = float(d.get('k3', 0.0))
            if a.rectified:
                D = [0.0, 0.0, 0.0, 0.0]; k3 = 0.0   # images pre-rectified with the full model of this set
            if abs(k3) > 0:
                if not a.drop_k3: sys.exit(f'{c}: k3={k3} != 0 but OpenVINS supports only k1 k2 p1 p2 (use --drop_k3 to drop it)')
                print(f'WARNING: {c}: dropping k3={k3} (unsupported by OpenVINS)')
        else:
            K = kal[c]['intrinsics']; D = kal[c]['distortion_coeffs']; print(f'{c}: not in {a.intrinsics}, using Kalibr values')
        cams[c] = ([float(x) for x in K], [float(x) for x in D])
    ov = os.path.join(a.out_dir, 'openvins'); os.makedirs(ov, exist_ok=True)
    # ---- OpenVINS
    shutil.copy(os.path.join(HERE, 'templates', 'openvins_estimator_config.yaml'), os.path.join(ov, 'estimator_config.yaml'))
    shutil.copy(os.path.join(HERE, 'templates', 'openvins_kalibr_imu_chain.yaml'), os.path.join(ov, 'kalibr_imu_chain.yaml'))
    out = ['%YAML:1.0', '', f'# generated by make_vio_config.py from {a.intrinsics}' + (' (pre-rectified images, zero distortion)' if a.rectified else ''),
           f'# T_cam_imu / timeshift_cam_imu / T_cn_cnm1 fixed from {os.path.relpath(KAL, ROOT)}/calib-camchain-imu0-cam.yaml', '']
    for c, topic in (('cam0', '/sensors/cam0/image_raw'), ('cam1', '/sensors/cam1/image_raw')):
        k = kal[c]; K, D = cams[c]
        out += [f'{c}:', '  T_cam_imu:', mat_rows(k['T_cam_imu']), f"  cam_overlaps: {k['cam_overlaps']}", '  camera_model: pinhole',
                f'  distortion_coeffs: {D}', '  distortion_model: radtan', f'  intrinsics: {K}', f'  resolution: {list(RES)}',
                f'  rostopic: {topic}', f"  timeshift_cam_imu: {k['timeshift_cam_imu']}"]
        if 'T_cn_cnm1' in k: out += ['  T_cn_cnm1:', mat_rows(k['T_cn_cnm1'])]
    open(os.path.join(ov, 'kalibr_imucam_chain.yaml'), 'w').write('\n'.join(out) + '\n')
    print('wrote', ov)
if __name__ == '__main__':
    main()
